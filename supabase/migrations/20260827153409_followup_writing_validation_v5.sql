  v_areas text[] := case btrim(coalesce(p_stuck_area,''))
    when '리딩' then array['리딩'] when '리스닝' then array['리스닝','리딩']
    when '라이팅' then array['라이팅'] when '스피킹' then array['스피킹']
    when '기타' then array['general'] else null end;
  v_a text;
  v_b text;
  v_count integer;
begin
  with bag as (
    select 0 copy_no,m.* from public.story_materials m where m.gwang='A'
    union all select x,m.* from generate_series(1,3) x cross join public.story_materials m
      where m.gwang='A' and v_areas is not null and m.area=any(v_areas)
  )
  select count(*) into v_count from bag;
  with bag as (
    select 0 copy_no,m.* from public.story_materials m where m.gwang='A'
    union all select x,m.* from generate_series(1,3) x cross join public.story_materials m
      where m.gwang='A' and v_areas is not null and m.area=any(v_areas)
  )
  select id into v_a from bag order by copy_no,sort_order offset (v_seed % v_count) limit 1;

  with bag as (
    select 0 copy_no,m.* from public.story_materials m where m.gwang='B'
    union all select x,m.* from generate_series(1,3) x cross join public.story_materials m
      where m.gwang='B' and v_areas is not null and m.area=any(v_areas)
  )
  select count(*) into v_count from bag;
  with bag as (
    select 0 copy_no,m.* from public.story_materials m where m.gwang='B'
    union all select x,m.* from generate_series(1,3) x cross join public.story_materials m
      where m.gwang='B' and v_areas is not null and m.area=any(v_areas)
  )
  select id into v_b from bag order by copy_no,sort_order
    offset ((v_seed/8)::bigint % v_count) limit 1;
  return array[v_a,v_b];
end;
$$;

create or replace function public.followup_call_name(p_full_name text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_name text := btrim(coalesce(p_full_name,''));
  v_compound_surnames text[] := array['남궁','황보','제갈','사공','선우','서문','독고','동방'];
begin
  if v_name !~ '^[가-힣]{2,4}$' then
    return null;
  end if;
  if char_length(v_name)=2 and v_name=any(v_compound_surnames) then
    return null;
  end if;
  if char_length(v_name) in (3,4) and left(v_name,2)=any(v_compound_surnames) then
    return substring(v_name from 3);
  end if;
  if char_length(v_name)=4 then
    return null;
  end if;
  return substring(v_name from 2);
end;
$$;

create or replace function public.followup_get_writing_context(p_job_id uuid)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_job public.followup_jobs%rowtype;
  v_app public.applications%rowtype;
  v_runtime public.followup_runtime%rowtype;
  v_existing public.followup_writing_inputs%rowtype;
  v_dates record;
  v_review record;
  v_review_id text;
  v_review_json jsonb;
  v_material_ids text[] := '{}';
  v_materials jsonb := '[]'::jsonb;
  v_attachment_id text;
  v_attachment jsonb;
  v_score record;
  v_excerpt text;
  v_actual_start date;
  v_context jsonb;
  v_hash text;
  v_call_name text;
  v_next_attempt integer;
  v_rule_version text := 'f5000579c81245fc2510d1f1c81e2950';
  v_previous jsonb := '[]'::jsonb;
begin
  select * into v_runtime from public.followup_runtime where singleton_id=1;
  if not found or v_runtime.operation_mode <> 'observe' or v_runtime.send_locked is distinct from true then
    raise exception 'writing requires operation_mode=observe and send_locked=true';
  end if;
  select * into v_job from public.followup_jobs where id=p_job_id for update;
  if not found then raise exception 'job not found'; end if;
  select * into v_existing from public.followup_writing_inputs where job_id=p_job_id;
  if found and v_job.status <> 'scheduled' then
    return v_existing.writing_context || jsonb_build_object(
      'context_hash',v_existing.context_hash,
      'outcome',v_job.status
    );
  end if;
  if v_job.draft_due_at is not null and now() < v_job.draft_due_at then
    raise exception 'writing context is not due yet';
  end if;
  if v_job.fresh_until_at is not null and now() >= v_job.fresh_until_at then
    perform public.followup_hold_job(p_job_id,gen_random_uuid(),'작성 가능 기간 만료: 관리자 확인 필요');
    return jsonb_build_object('outcome','held','reason','writing_window_expired');
  end if;
  if v_existing.job_id is not null then
    select coalesce(max(a.attempt_no),0)+1 into v_next_attempt
    from public.followup_draft_attempts a where a.job_id=p_job_id;
    return v_existing.writing_context || jsonb_build_object(
      'context_hash',v_existing.context_hash,
      'outcome','ready',
      'next_attempt',v_next_attempt
    );
  end if;
  if v_job.status <> 'scheduled' then raise exception 'writing context requires scheduled job'; end if;
  if v_job.candidate_first_seen_at is null or v_job.candidate_basis is null
     or not (v_job.candidate_basis ? 'draft_due_at') or not (v_job.candidate_basis ? 'scheduled_at')
     or v_job.scheduled_at is null or v_job.draft_due_at is null or v_job.fresh_until_at is null
     or (v_job.stage <> 'stage1' and v_job.deadline_snapshot is null) then
    perform public.followup_hold_job(p_job_id,gen_random_uuid(),'작성 근거가 빈 과거 작업: 추측 금지');
    return jsonb_build_object('outcome','held','reason','missing_candidate_basis');
  end if;
  select * into v_app from public.applications where id=v_job.application_id and deleted is false;
  if not found then
    perform public.followup_hold_job(p_job_id,gen_random_uuid(),'신청 자료 없음: 추측 금지');
    return jsonb_build_object('outcome','held','reason','application_missing');
  end if;
  if (v_job.stage='stage1' and v_app.application_type is distinct from 'book_only')
     or (v_job.stage<>'stage1' and v_app.application_type is distinct from 'challenge') then
    perform public.followup_hold_job(p_job_id,gen_random_uuid(),'신청 종류와 작성 단계 불일치');
    return jsonb_build_object('outcome','held','reason','application_type_mismatch');
  end if;
  v_call_name := public.followup_call_name(v_app.name);
  if nullif(btrim(v_call_name),'') is null then
    perform public.followup_hold_job(p_job_id,gen_random_uuid(),'호출 이름 형식 확인 필요');
    return jsonb_build_object('outcome','held','reason','call_name_invalid');
  end if;
  select * into v_dates from public.followup_writing_dates(v_job.scheduled_at);
  if v_dates.start_sunday is null then raise exception 'writing dates unavailable'; end if;
  if nullif(btrim(v_app.schedule_start),'') is not null then
    if btrim(v_app.schedule_start) !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}' then
      perform public.followup_hold_job(p_job_id,gen_random_uuid(),'실제 시작일 형식 확인 필요');
      return jsonb_build_object('outcome','held','reason','schedule_start_invalid');
    end if;
    v_actual_start := left(btrim(v_app.schedule_start),10)::date;
    if v_actual_start <> v_dates.start_sunday then
      perform public.followup_hold_job(p_job_id,gen_random_uuid(),'실제 시작일과 계산 일요일 불일치');
      return jsonb_build_object('outcome','held','reason','schedule_start_conflict');
    end if;
  end if;
  if v_job.stage='stage2' and (v_app.analysis_status is distinct from '승인'
      or nullif(btrim(v_app.analysis_content),'') is null) then
    perform public.followup_hold_job(p_job_id,gen_random_uuid(),'승인된 개별분석 없음');
    return jsonb_build_object('outcome','held','reason','approved_analysis_missing');
  end if;
  if v_job.stage in ('stage2','stage3a','stage3b') then
    v_excerpt := public.followup_writing_excerpt(v_app.analysis_content,
      case when v_job.stage='stage2' then 360 else 240 end);
  end if;
  if v_job.stage='stage1' then
    select * into v_review from public.followup_select_review(
      v_app.id,v_app.current_score::text,v_app.target_score,v_app.referral_source,
      case when coalesce(v_app.created_at,0)>0 then to_timestamp(v_app.created_at/1000.0)
           else public.followup_try_timestamptz(v_app.submitted_date) end,
      v_job.scheduled_at);
    v_review_id := v_review.review_id;
    select to_jsonb(r) || jsonb_build_object('selection_mode',v_review.selection_mode,'reached_target',v_review.reached_target)
      into v_review_json from public.followup_review_assets r where r.review_id=v_review.review_id;
    v_material_ids := public.followup_select_materials(v_app.id,v_app.stuck_area);
    select coalesce(jsonb_agg(to_jsonb(m) order by array_position(v_material_ids,m.id)),'[]'::jsonb)
      into v_materials from public.story_materials m where m.id=any(v_material_ids);
    select * into v_score from public.followup_writing_score(v_app.target_score,true);
    if v_score.is_blank or v_score.score_kind='old' then v_attachment_id := 'score-conversion-2026-v1'; end if;
  end if;
  if v_attachment_id is not null then
    select to_jsonb(a) into v_attachment from public.followup_attachment_assets a
    where a.asset_id=v_attachment_id and a.is_active;
    if v_attachment is null then raise exception 'required attachment unavailable'; end if;
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('stage',x.stage,'subject',x.subject,'body',x.body)
    order by x.created_at),'[]'::jsonb) into v_previous
  from (
    select j.stage,m.subject,m.body,m.created_at
    from public.followup_jobs j join public.followup_messages m on m.job_id=j.id
    where j.id<>v_job.id and public.followup_normalize_email(j.email)=public.followup_normalize_email(v_job.email)
      and j.status not in ('canceled','skipped','failed')
  ) x;
  v_context := jsonb_build_object(
    'job_id',v_job.id,'application_id',v_job.application_id,'stage',v_job.stage,
    'rule_version',v_rule_version,'name',v_call_name,'scheduled_at',v_job.scheduled_at,
    'deadline_thursday',v_dates.deadline_thursday,'start_sunday',v_dates.start_sunday,
    'cta_url',case v_job.stage when 'stage1' then 'https://eonfl.com/application-form.html'
      else 'https://eonfl.com/application-detail.html?id='||v_job.application_id::text||
        case v_job.stage when 'stage2' then '#step2' when 'stage3a' then '#step3' else '#step4' end end,
    'stage1_data',case when v_job.stage='stage1' then jsonb_build_object(
      'progress_percent',v_job.progress_percent,'current_score',v_app.current_score,
      'target_score',v_app.target_score,'referral_source',v_app.referral_source,'stuck_area',v_app.stuck_area) end,
    'analysis_excerpt',v_excerpt,
    'analysis_fallback',v_job.stage in ('stage3a','stage3b') and v_excerpt is null,
    'review',v_review_json,'materials',v_materials,'attachment',v_attachment,
    'previous_messages',v_previous
  );
  v_hash := encode(extensions.digest(convert_to(v_context::text,'UTF8'),'sha256'),'hex');
  insert into public.followup_writing_inputs(job_id,application_id,stage,rule_version,
    selection_seed,writing_context,used_review_id,used_material_ids,attachment_asset_id,context_hash)
  values(v_job.id,v_job.application_id,v_job.stage,v_rule_version,public.followup_fnv1a32(v_job.application_id::text),
    v_context,v_review_id,v_material_ids,v_attachment_id,v_hash);
  return v_context || jsonb_build_object('context_hash',v_hash,'outcome','ready','next_attempt',1);
end;
$$;

create or replace function public.followup_record_writing_attempt(
  p_job_id uuid, p_request_id uuid, p_attempt_no integer,
  p_subject text, p_body text, p_self_check jsonb,
  p_machine_check_result jsonb, p_human_check_result jsonb,
  p_run_id uuid default null
)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_job public.followup_jobs%rowtype;
  v_input public.followup_writing_inputs%rowtype;
  v_existing public.followup_draft_attempts%rowtype;
  v_payload_hash text;
  v_machine_pass boolean;
  v_human_measured boolean;
  v_human_pass boolean;
  v_server_pass boolean;
  v_failed text[] := '{}';
  v_next integer;
  v_result jsonb;
  v_saved jsonb;
  v_cta text;
  v_lex record;
  v_masked text;
  v_url_match text[];
  v_url text;
  v_review_url text;
  v_score_match text[];
  v_score_value integer;
  v_score_level numeric;
  v_date_match text[];
  v_nearest_date date;
  v_sent_date date;
  v_dates record;
  v_check_names text[] := array['길이',':) 필수','이온드림','제목형식','후기id↔숫자','CTA정합','링크형식','점수병기','환산표첨부','본문날짜','금지어·부호·담화예고'];
  v_human_check_names text[] := array['tone','story','duplicate','date_stage','one_to_one'];
begin
  if p_job_id is null or p_request_id is null or p_attempt_no not between 1 and 4 then
    raise exception 'job, request, and attempt 1..4 are required';
  end if;
  select * into v_existing from public.followup_draft_attempts where request_id=p_request_id;
  v_payload_hash := encode(extensions.digest(convert_to(concat_ws(E'\n',p_job_id,p_attempt_no,p_subject,p_body,
    coalesce(p_self_check,'{}'::jsonb)::text,coalesce(p_machine_check_result,'{}'::jsonb)::text,
    coalesce(p_human_check_result,'{}'::jsonb)::text),'UTF8'),'sha256'),'hex');
  if found then
    if v_existing.job_id<>p_job_id or v_existing.attempt_no<>p_attempt_no or v_existing.payload_hash<>v_payload_hash then
      raise exception 'request_id reuse with different attempt payload';
    end if;
    return v_existing.result;
  end if;
  select * into v_job from public.followup_jobs where id=p_job_id for update;
  if not found then raise exception 'job not found'; end if;
  if v_job.status <> 'scheduled' then
    return jsonb_build_object('outcome',v_job.status);
  end if;
  if v_job.draft_due_at is not null and now() < v_job.draft_due_at then
    raise exception 'writing attempt is not due yet';
  end if;
  if v_job.fresh_until_at is not null and now() >= v_job.fresh_until_at then
    perform public.followup_hold_job(p_job_id,p_request_id,'작성 가능 기간 만료: 관리자 확인 필요',p_run_id);
    return jsonb_build_object('outcome','held','reason','writing_window_expired');
  end if;
  select * into v_input from public.followup_writing_inputs where job_id=p_job_id;
  if not found then raise exception 'fixed writing context missing'; end if;
  select coalesce(max(attempt_no),0)+1 into v_next from public.followup_draft_attempts where job_id=p_job_id;
  if p_attempt_no<>v_next then raise exception 'attempt must be sequential: expected %',v_next; end if;
  if nullif(btrim(p_subject),'') is null or nullif(btrim(p_body),'') is null then v_failed:=array_append(v_failed,'subject_or_body_empty'); end if;
  v_cta := v_input.writing_context->>'cta_url';
  if p_subject <> (case v_job.stage when 'stage1' then (v_input.writing_context->>'name')||'님, 이온입니다'
      when 'stage2' then (v_input.writing_context->>'name')||'님, 개별분석 관련해서 연락드립니다!'
      when 'stage3a' then (v_input.writing_context->>'name')||'님, 계약서 관련해서 연락드립니다!'
      else (v_input.writing_context->>'name')||'님, 등록 관련해서 연락드립니다!' end) then
    v_failed:=array_append(v_failed,'title_format');
  end if;
  if position(':)' in p_body)=0 then v_failed:=array_append(v_failed,'smiley'); end if;
  if position('이온 드림' in p_body)=0 then v_failed:=array_append(v_failed,'signoff'); end if;
  if right(btrim(p_body),length(v_cta))<>v_cta then v_failed:=array_append(v_failed,'cta_end'); end if;
  if char_length(p_body)>(case v_job.stage when 'stage1' then 1600 when 'stage2' then 1100 else 700 end) then
    v_failed:=array_append(v_failed,'length');
  end if;
  if v_input.used_review_id is not null and position((v_input.writing_context#>>'{review,url}') in p_body)=0 then
    v_failed:=array_append(v_failed,'assigned_review_missing');
  end if;
  if v_input.attachment_asset_id is not null and not exists(select 1 from public.followup_attachment_assets a
    where a.asset_id=v_input.attachment_asset_id and a.is_active) then v_failed:=array_append(v_failed,'attachment_missing'); end if;
  if v_input.attachment_asset_id is not null and not (p_body like '%환산표%' and p_body like '%첨부%') then
    v_failed:=array_append(v_failed,'attachment_copy_missing');
  elsif v_input.attachment_asset_id is null and p_body like '%환산표%' and p_body like '%첨부%' then
    v_failed:=array_append(v_failed,'attachment_copy_unexpected');
  end if;

  v_review_url:=v_input.writing_context#>>'{review,url}';
  for v_url_match in select regexp_matches(p_body,'https?://[^[:space:])]+','g') loop
    v_url:=regexp_replace(v_url_match[1],'[.,]+$','');
    if v_url<>v_cta and (v_review_url is null or v_url<>v_review_url) then
      v_failed:=array_append(v_failed,'unapproved_url');
    end if;
  end loop;

  v_masked:=p_body;
  for v_lex in select * from public.lexicon where category='whitelist_exception' order by id loop
    v_masked:=replace(v_masked,v_lex.pattern,repeat(' ',char_length(v_lex.pattern)));
  end loop;
  v_masked:=regexp_replace(v_masked,'https?://[^[:space:])]+',repeat(' ',8),'g');
  v_masked:=regexp_replace(v_masked,'[‒–―−]','—','g');
  v_masked:=regexp_replace(v_masked,'[„‟«»″〝〞「」『』]','"','g');
  for v_lex in
    select * from public.lexicon
    where category<>'whitelist_exception' and match_type<>'semantic'
      and scope in ('all',v_job.stage)
    order by id
  loop
    if (v_lex.pattern='(?<!\d):(?![)\d])' and position(':' in regexp_replace(v_masked,'([0-9]:[0-9]|:\))','','g'))>0)
       or (v_lex.pattern<>'(?<!\d):(?![)\d])' and v_lex.match_type='substring' and position(v_lex.pattern in v_masked)>0)
       or (v_lex.match_type='regex' and v_lex.pattern<>'(?<!\d):(?![)\d])' and v_masked ~ v_lex.pattern)
       or (v_lex.match_type='word_boundary' and v_masked ~ ('(^|[^[:alnum:]가-힣_])'||v_lex.pattern||'(은|는|이|가|을|를|의|에|와|과|도|만|으로|로|에서|에게|한테|께|처럼|보다|까지|부터|조차|마저|이나|나)?($|[^[:alnum:]가-힣_])')) then
      v_failed:=array_append(v_failed,'lexicon:'||v_lex.id::text);
    end if;
  end loop;

  for v_score_match in select regexp_matches(p_body,'([0-9]{1,3})[[:space:]]*점','g') loop
    v_score_value:=v_score_match[1]::integer;
    if v_input.used_review_id is not null and exists(
      select 1 from public.followup_review_assets r where r.review_id=v_input.used_review_id
        and v_score_value in (r.start_score,r.final_score)
    ) then continue; end if;
    select (m)[2]::numeric into v_score_level
    from regexp_matches(p_body,'('||v_score_value||')[[:space:]]*점[^0-9]{0,12}([2-6](?:\.0|\.5))[[:space:]]*레벨','g') m limit 1;
    if v_score_level is null or not exists(select 1 from public.score_table s
      where s.level=v_score_level and v_score_value between s.cutoff_low and s.cutoff_high) then
      v_failed:=array_append(v_failed,'raw_score_or_conversion');
    end if;
    v_score_level:=null;
  end loop;

  select * into v_dates from public.followup_writing_dates(v_job.scheduled_at);
  if p_body like '%목요일%' and position(extract(month from v_dates.deadline_thursday)::integer||'월 '
      ||extract(day from v_dates.deadline_thursday)::integer||'일' in p_body)=0
     and position(extract(month from v_dates.deadline_thursday)::integer||'월'
      ||extract(day from v_dates.deadline_thursday)::integer||'일' in p_body)=0 then
    v_failed:=array_append(v_failed,'thursday_mismatch');
  end if;
  for v_date_match in select regexp_matches(p_body,'([0-9]{1,2})월[[:space:]]*([0-9]{1,2})일','g') loop
    v_sent_date:=(v_job.scheduled_at at time zone 'Asia/Seoul')::date;
    begin
      select make_date(y,v_date_match[1]::integer,v_date_match[2]::integer) into v_nearest_date
      from generate_series(extract(year from v_sent_date)::integer-1,
        extract(year from v_sent_date)::integer+1) y
      order by abs(make_date(y,v_date_match[1]::integer,v_date_match[2]::integer)-v_sent_date)
      limit 1;
    exception when others then
      v_failed:=array_append(v_failed,'invalid_body_date');
      continue;
    end;
    if v_nearest_date < v_sent_date then
      v_failed:=array_append(v_failed,'past_body_date');
    end if;
  end loop;
  v_machine_pass := coalesce((p_machine_check_result->>'pass')::boolean,false)
    and jsonb_typeof(p_machine_check_result->'results')='array'
    and case when jsonb_typeof(p_machine_check_result->'results')='array'
      then jsonb_array_length(p_machine_check_result->'results')=11 else false end
    and not exists(select 1 from jsonb_array_elements(case
      when jsonb_typeof(p_machine_check_result->'results')='array' then p_machine_check_result->'results'
      else '[]'::jsonb end) e
      where coalesce((e->>'pass')::boolean,false)=false
         or nullif(btrim(e->>'reason'),'') is null
         or nullif(btrim(e->>'evidence'),'') is null)
    and (select array_agg(distinct e->>'check' order by e->>'check')
      from jsonb_array_elements(case
        when jsonb_typeof(p_machine_check_result->'results')='array' then p_machine_check_result->'results'
        else '[]'::jsonb end) e)
      = (select array_agg(x order by x) from unnest(v_check_names) x);
  v_human_measured := coalesce((p_human_check_result->>'measured')::boolean,false);
  v_human_pass := v_human_measured and coalesce((p_human_check_result->>'pass')::boolean,false)
    and jsonb_typeof(p_human_check_result->'checks')='array'
    and case when jsonb_typeof(p_human_check_result->'checks')='array'
      then jsonb_array_length(p_human_check_result->'checks')=5 else false end
    and not exists(select 1 from jsonb_array_elements(case
      when jsonb_typeof(p_human_check_result->'checks')='array' then p_human_check_result->'checks'
      else '[]'::jsonb end) e
      where coalesce((e->>'pass')::boolean,false)=false
         or nullif(btrim(e->>'reason'),'') is null
         or nullif(btrim(e->>'evidence'),'') is null)
    and (select array_agg(distinct e->>'check' order by e->>'check')
      from jsonb_array_elements(case
        when jsonb_typeof(p_human_check_result->'checks')='array' then p_human_check_result->'checks'
        else '[]'::jsonb end) e)
      = (select array_agg(x order by x) from unnest(v_human_check_names) x);
  v_server_pass := cardinality(v_failed)=0;
  if not v_human_pass and v_human_measured then
    perform public.followup_hold_job(p_job_id,p_request_id,'사람 판단 검사 실패',p_run_id);
    v_result:=jsonb_build_object('outcome','held','reason','human_check_failed');
  elsif v_machine_pass and v_human_pass and v_server_pass then
    v_saved:=public.followup_save_draft(p_job_id,p_request_id,p_subject,p_body,
      v_input.attachment_asset_id,v_input.rule_version,p_run_id);
    update public.followup_messages set
      ref_materials=jsonb_build_object(
        'used_review_id',v_input.used_review_id,
        'used_materials',(select coalesce(jsonb_agg(to_jsonb(m)),'[]'::jsonb)
          from public.story_materials m where m.id=any(v_input.used_material_ids))
      ),
      validation_evidence=jsonb_build_object(
        'self_check',coalesce(p_self_check,'{}'::jsonb),
        'machine',p_machine_check_result,
        'human',p_human_check_result,
        'server_failed',v_failed,
        'writing_context_hash',v_input.context_hash,
        'attempt_count',p_attempt_no
      ),
      validation_passed_at=now()
    where job_id=p_job_id;
    v_result:=jsonb_build_object('outcome','awaiting_review','job',v_saved);
  elsif p_attempt_no=4 then
    perform public.followup_hold_job(p_job_id,p_request_id,'기계 검사 4회 실패',p_run_id);
    v_result:=jsonb_build_object('outcome','held','reason','machine_check_failed_four_times','server_failed',v_failed);
  else
    v_result:=jsonb_build_object('outcome','rewrite','next_attempt',p_attempt_no+1,'server_failed',v_failed);
  end if;
  insert into public.followup_draft_attempts(job_id,attempt_no,request_id,subject,body,self_check,
    machine_check_result,human_check_result,payload_hash,outcome,result)
  values(p_job_id,p_attempt_no,p_request_id,p_subject,p_body,coalesce(p_self_check,'{}'::jsonb),
    coalesce(p_machine_check_result,'{}'::jsonb),coalesce(p_human_check_result,'{}'::jsonb),
    v_payload_hash,v_result->>'outcome',v_result);
  return v_result;
end;
$$;

