## 3. 문단·문장 리듬

- **문단 = 관련된 2~4문장 한 덩어리.** 한 줄에 한 문장씩 떨어뜨리면 가사처럼 보여 실패. 한두 문장마다 줄바꿈하는 AI식 나누기 금지. 같은 이야기면 한 문단에 이어 쓰고, 주제가 실제로 바뀌거나 읽다가 한 번 쉬는 게 자연스러운 지점에서만 나눈다. 문단 수를 보기 좋게 맞추려고 억지로 나누지 않는다. (통합)
- **문장 길이는 들쭉날쭉.** 짧게 끝나는 문장도 쓰고, 설명이 필요한 부분은 한 문장 안에서 조금 길게 이어가도 된다. 모든 문장을 비슷한 길이로 반듯하게 만들지 마라 — 전부 똑같이 톡톡 끊으면 AI·광고 티. '한 문장 25자' 같은 하드룰 금지(초사고 원문의 해당 조항은 이 편지에 적용하지 않는다). (통합)
- **이따금 마침표를 연결어로 흘려보낸다**: "~있어요. 그래서" → "~있는 게,", "~거예요. 근데" → "~건데,". 다 잇지도 말고 적당한 때 이따금. (기존)
- **한 문장 안에 이유·조건·다음 행동을 이어 말해도 된다.** 한 문장마다 새 정보 하나씩 배치하려고 잘게 끊지 마라. ✗ "시험은 9월 첫째 주에 보세요. 그 후 결과를 확인하세요. 첨삭은 9월 13일부터 시작하세요." ✓ "9월 첫째 주 시험 먼저 보시고, 결과 확인한 다음 9월 13일부터 첨삭 시작하시면 될 것 같아요." (제안)
- 문장을 너무 정돈하지 마라. 모든 문장이 문법책 예문처럼 완벽하면 오히려 AI 티. 말하면서 쓰는 정도의 이어짐은 남긴다. **단, 맞춤법을 일부러 틀리거나 오타를 만들지는 않는다.** (제안)

